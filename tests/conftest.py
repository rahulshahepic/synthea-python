"""Shared pytest fixtures.

Parity tests compare Python output with goldens generated by the Java reference
(``parity/gen_golden.sh`` writes them to ``parity/golden/``).

* Locally, a parity test whose golden directory is missing is SKIPPED, so agents
  without a JDK can still run the unit tests.
* In CI ``PARITY_REQUIRED=1`` is set, and a missing golden is a FAILURE.
"""

from __future__ import annotations

import os
from collections.abc import Callable
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
GOLDEN_ROOT = REPO_ROOT / "parity" / "golden"


@pytest.fixture
def golden() -> Callable[[str], Path]:
    """Return a function mapping a probe name (e.g. ``"JavaRandomProbe"``) to its golden dir."""

    def _golden(probe: str) -> Path:
        path = GOLDEN_ROOT / probe
        if not path.is_dir():
            msg = f"golden output for {probe} not found at {path}; run parity/gen_golden.sh"
            if os.environ.get("PARITY_REQUIRED") == "1":
                pytest.fail(msg)
            pytest.skip(msg)
        return path

    return _golden
