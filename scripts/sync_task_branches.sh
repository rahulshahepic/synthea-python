#!/usr/bin/env bash
# Merge origin/main into every open PR branch named task/* (see .github/workflows/sync-task-branches.yml).
# Needs: gh (GH_TOKEN), REPO=owner/name, uv. Never rebases, never force-pushes.
set -uo pipefail
git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git fetch -q origin '+refs/heads/*:refs/remotes/origin/*'

# Make sure every protocol label exists (gh refuses to add labels that don't exist).
while read -r name color; do
  gh label create "$name" --repo "$REPO" --color "$color" --force >/dev/null 2>&1 || true
done <<'LABELS'
type:task 5319E7
status:ready 0E8A16
status:blocked B60205
status:startable C2E0C6
status:stale D93F0B
status:claimed FBCA04
agent:muse 1D76DB
agent:chatgpt 1D76DB
review:needed FBCA04
review:changes-requested D93F0B
review:approved 0E8A16
needs:manual-merge D93F0B
LABELS

# Files that are safe to resolve mechanically (besides .gitattributes merge=union files).
REGENERATED="uv.lock"

prs="$(gh pr list --repo "$REPO" --state open --base main --limit 200 \
  --json number,headRefName,isCrossRepository,labels \
  --jq '.[] | select(.headRefName | startswith("task/")) | select(.isCrossRepository | not)
        | "\(.number) \(.headRefName) \([.labels[].name] | join(","))"')"

while read -r num branch labels; do
  [[ -z "${num:-}" ]] && continue
  echo "::group::#$num $branch"
  git checkout -q -B "$branch" "origin/$branch"
  if git merge-base --is-ancestor origin/main HEAD; then
    echo "already contains main"; echo "::endgroup::"; continue
  fi
  if ! git merge -q --no-edit -m "Merge main into $branch (auto-sync)" origin/main; then
    mapfile -t conflicted < <(git diff --name-only --diff-filter=U)
    unresolved=()
    for f in "${conflicted[@]}"; do
      if [[ " $REGENERATED " == *" $f "* ]]; then
        git checkout -q --theirs -- "$f"   # placeholder; regenerated below
      else
        unresolved+=("$f")
      fi
    done
    if (( ${#unresolved[@]} > 0 )); then
      git merge --abort
      echo "real conflict in: ${unresolved[*]}"
      if [[ ",$labels," != *",needs:manual-merge,"* ]]; then
        gh pr edit "$num" --repo "$REPO" --add-label "needs:manual-merge"
        gh pr comment "$num" --repo "$REPO" --body "⚠️ Auto-sync could not merge \`main\` into \`$branch\`: conflict in $(printf '`%s` ' "${unresolved[@]}").
Agent: merge \`origin/main\` into your branch and resolve it (AGENTS.md §4), then remove the \`needs:manual-merge\` label. CI still runs on your pushes in the meantime.

---
_Generated by [Claude Code](https://claude.ai/code)_"
      fi
      echo "::endgroup::"; continue
    fi
    uv lock -q && git add uv.lock
    git commit -q --no-edit
  fi
  if ! uv lock --locked -q 2>/dev/null; then   # lock stale after combining both sides' deps
    uv lock -q && git add uv.lock && git commit -q -m "Regenerate uv.lock after auto-sync"
  fi
  pushed_ok=0
  git push -q origin "HEAD:refs/heads/$branch" && pushed_ok=1
  if [[ "$pushed_ok" == "1" ]]; then
    echo "pushed $(git rev-parse --short HEAD)"
  fi
  if [[ "$pushed_ok" == "1" && "${SYNC_WITH_PAT:-false}" != "true" ]]; then
    # Fallback without SYNC_TOKEN: pushes made with GITHUB_TOKEN don't trigger workflows,
    # so dispatch them explicitly. (Branch rules may not count these dispatched checks.)
    gh workflow run ci.yml --repo "$REPO" --ref "$branch"
    gh workflow run review-gate.yml --repo "$REPO" --ref "$branch" -f pr="$num"
    # workflow_run doesn't fire for runs started with GITHUB_TOKEN, so route the PR to the
    # reviewer explicitly once that CI run finishes (no-op unless it's labelled review:needed).
    if [[ ",$labels," == *",review:needed,"* || ",$labels," == *",review:approved,"* ]]; then
      sleep 5   # let the dispatched CI run register before review-dispatch looks for it
      gh workflow run review-dispatch.yml --repo "$REPO" --ref main -f branch="$branch" -f wait_for_ci=true
    fi
  fi
  if [[ "$pushed_ok" == "1" ]]; then
    if [[ ",$labels," == *",needs:manual-merge,"* ]]; then
      gh pr edit "$num" --repo "$REPO" --remove-label "needs:manual-merge"
    fi
  else
    echo "push rejected (agent pushed meanwhile); next main push will retry"
  fi
  echo "::endgroup::"
done <<<"$prs"
