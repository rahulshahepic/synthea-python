#!/usr/bin/env bash
# See .github/workflows/review-dispatch.yml. Needs GH_TOKEN, REPO, BRANCH.
set -euo pipefail
read -r num sha labels < <(gh pr list --repo "$REPO" --state open --head "$BRANCH" --limit 1 \
  --json number,headRefOid,labels \
  --jq '.[0] | select(. != null) | [.number, .headRefOid, ([.labels[].name] | join(","))] | @tsv') || true
if [[ -z "${num:-}" ]]; then echo "no open PR for $BRANCH"; exit 0; fi
if [[ ",$labels," != *",review:needed,"* ]]; then echo "#$num not waiting for review"; exit 0; fi

# Latest CI run for the PR head commit.
run="$(gh run list --repo "$REPO" --workflow ci.yml --commit "$sha" --limit 1 \
  --json databaseId,status,conclusion,url --jq '.[0] // empty')"
if [[ -z "$run" ]]; then echo "CI not started for $sha yet"; exit 0; fi
status="$(jq -r .status <<<"$run")"; conclusion="$(jq -r .conclusion <<<"$run")"; url="$(jq -r .url <<<"$run")"
if [[ "$status" != "completed" ]]; then echo "CI still running for $sha"; exit 0; fi

if [[ "$conclusion" != "success" ]]; then
  gh pr edit "$num" --repo "$REPO" --remove-label "review:needed" --add-label "review:changes-requested"
  gh pr comment "$num" --repo "$REPO" --body "🔴 CHANGES REQUESTED (automated, ${sha:0:7})

1. CI is **$conclusion** on the head commit: $url
   Fix it, push, and re-request review once CI is green (AGENTS.md §5, §7). The reviewer only sees PRs whose CI is green.

---
_Generated by [Claude Code](https://claude.ai/code)_"
  echo "bounced #$num: CI $conclusion"; exit 0
fi

echo "#$num is green and waiting for review"
if [[ -n "${TRIGGER_URL:-}" && -n "${TRIGGER_TOKEN:-}" ]]; then
  jq -n --arg t "Review PR #$num (head ${sha:0:7}) in $REPO: CI is green and it is labelled review:needed. Run the review routine in docs/REVIEW.md." \
    '{text: $t}' | curl -fsS -X POST "$TRIGGER_URL" -H "Authorization: Bearer $TRIGGER_TOKEN" \
      -H "anthropic-beta: experimental-cc-routine-2026-04-01" \
      -H "anthropic-version: 2023-06-01" \
      -H "Content-Type: application/json" --data @- >/dev/null && echo "reviewer notified"
else
  echo "REVIEWER_TRIGGER_URL/TOKEN not set; the scheduled routine will pick it up"
fi
