#!/usr/bin/env bash
# See .github/workflows/review-dispatch.yml. Needs GH_TOKEN, REPO, BRANCH.
set -euo pipefail
read -r num sha labels < <(gh pr list --repo "$REPO" --state open --head "$BRANCH" --limit 1 \
  --json number,headRefOid,labels \
  --jq '.[0] | select(. != null) | [.number, .headRefOid, ([.labels[].name] | join(","))] | @tsv') || true
if [[ -z "${num:-}" ]]; then echo "no open PR for $BRANCH"; exit 0; fi
if [[ ",$labels," == *",review:approved,"* ]]; then
  want="merge"     # approved, but the head moved (e.g. auto-sync): merge once CI is green
elif [[ ",$labels," == *",review:needed,"* ]]; then
  want="review"
else
  echo "#$num not waiting for review or merge"; exit 0
fi

# Latest CI run for the PR head commit.
run="$(gh run list --repo "$REPO" --workflow ci.yml --commit "$sha" --limit 1 \
  --json databaseId,status,conclusion,url --jq '.[0] // empty')"
if [[ -z "$run" ]]; then echo "CI not started for $sha yet"; exit 0; fi
status="$(jq -r .status <<<"$run")"; conclusion="$(jq -r .conclusion <<<"$run")"; url="$(jq -r .url <<<"$run")"
if [[ "$status" != "completed" ]]; then
  if [[ "${WAIT_FOR_CI:-}" == "true" ]]; then
    # Started by the sync bot: GitHub won't fire workflow_run for runs it dispatched,
    # so wait here for CI to finish instead.
    echo "waiting for CI on $sha"
    gh run watch "$(jq -r .databaseId <<<"$run")" --repo "$REPO" --exit-status >/dev/null || true
    run="$(gh run view "$(jq -r .databaseId <<<"$run")" --repo "$REPO" --json status,conclusion,url)"
    conclusion="$(jq -r .conclusion <<<"$run")"; url="$(jq -r .url <<<"$run")"
  else
    echo "CI still running for $sha"; exit 0
  fi
fi

if [[ "$conclusion" != "success" ]]; then
  gh pr edit "$num" --repo "$REPO" --remove-label "review:needed" --remove-label "review:approved" \
    --add-label "review:changes-requested"
  gh pr comment "$num" --repo "$REPO" --body "🔴 CHANGES REQUESTED (automated, ${sha:0:7})

1. CI is **$conclusion** on the head commit: $url
   Fix it, push, and re-request review once CI is green (AGENTS.md §5, §7). The reviewer only sees PRs whose CI is green.

---
_Generated by [Claude Code](https://claude.ai/code)_"
  echo "bounced #$num: CI $conclusion"; exit 0
fi

echo "#$num is green and waiting for $want"
if [[ "$want" == "merge" ]]; then
  # Approved earlier; any agent push would have removed review:approved, so the only new
  # commits are auto-sync merges from main. CI is green on this head: merge it.
  title="$(gh pr view "$num" --repo "$REPO" --json title --jq .title)"
  GH_TOKEN="${MERGE_TOKEN:-$GH_TOKEN}" gh pr merge "$num" --repo "$REPO" --squash \
    --subject "$title (#$num)" --match-head-commit "$sha"
  echo "merged #$num"
  if [[ -z "${MERGE_TOKEN:-}" ]]; then
    # Merges made with GITHUB_TOKEN don't trigger push workflows; run them explicitly.
    gh workflow run ci.yml --repo "$REPO" --ref main
    gh workflow run sync-task-branches.yml --repo "$REPO" --ref main
  fi
  exit 0
fi
msg="Review PR #$num (head ${sha:0:7}) in $REPO: CI is green and it is labelled review:needed. Run the review routine in docs/REVIEW.md."
if [[ -n "${TRIGGER_URL:-}" && -n "${TRIGGER_TOKEN:-}" ]]; then
  jq -n --arg t "$msg" '{text: $t}' | curl -fsS -X POST "$TRIGGER_URL" -H "Authorization: Bearer $TRIGGER_TOKEN" \
      -H "anthropic-beta: experimental-cc-routine-2026-04-01" \
      -H "anthropic-version: 2023-06-01" \
      -H "Content-Type: application/json" --data @- >/dev/null && echo "reviewer notified"
else
  echo "REVIEWER_TRIGGER_URL/TOKEN not set; the scheduled routine will pick it up"
fi
