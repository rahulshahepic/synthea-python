#!/usr/bin/env bash
# See .github/workflows/unblock-tasks.yml. Needs GH_TOKEN and REPO.
#
# For every open task issue, from its "### Depends on" (#N) references:
#   status:ready      every dependency is merged (issue closed)
#   status:startable  every dependency is merged or claimed: port against the T04 stubs now,
#                     ask for review once it turns status:ready
#   status:blocked    some dependency is not even claimed yet
# Claimed tasks are left alone, except that a claim with no push for STALE_HOURS gets the
# label status:stale and one comment, so a stuck agent is visible to the user and reviewer.
set -euo pipefail
STALE_HOURS="${STALE_HOURS:-24}"
gh label create status:startable --repo "$REPO" --color C2E0C6 --force >/dev/null 2>&1 || true
gh label create status:stale --repo "$REPO" --color D93F0B --force >/dev/null 2>&1 || true

issues="$(gh issue list --repo "$REPO" --state all --label type:task --limit 500 \
  --json number,state,labels,body)"
state_of() { jq -r --argjson n "$1" '.[] | select(.number == $n) | .state' <<<"$issues"; }
has_label() { jq -e --argjson n "$1" --arg l "$2" \
  '.[] | select(.number == $n) | any(.labels[]; .name == $l)' <<<"$issues" >/dev/null; }

for num in $(jq -r '.[] | select(.state == "OPEN") | .number' <<<"$issues"); do
  if has_label "$num" status:claimed; then
    # Stale-claim check: last commit on task/<N>.
    last="$(gh api "repos/$REPO/commits/task/$num" --jq '.commit.committer.date' 2>/dev/null || true)"
    if [[ -n "$last" ]]; then
      age_h=$(( ( $(date +%s) - $(date -d "$last" +%s) ) / 3600 ))
      if (( age_h >= STALE_HOURS )) && ! has_label "$num" status:stale; then
        gh issue edit "$num" --repo "$REPO" --add-label status:stale
        gh issue comment "$num" --repo "$REPO" --body "⏰ No push to \`task/$num\` for ${age_h}h. Marked \`status:stale\`. Owner: push your progress or comment why it's paused. The reviewer/user may reassign it.

---
_Generated by [Claude Code](https://claude.ai/code)_"
        echo "#$num stale (${age_h}h)"
      elif (( age_h < STALE_HOURS )) && has_label "$num" status:stale; then
        gh issue edit "$num" --repo "$REPO" --remove-label status:stale
      fi
    fi
    continue
  fi
  body="$(jq -r --argjson n "$num" '.[] | select(.number == $n) | .body' <<<"$issues")"
  deps="$(awk '/^### Depends on/{f=1; next} /^### /{f=0} f' <<<"$body" | grep -oE '\(#[0-9]+\)' | tr -d '(#)' || true)"
  want=status:ready; waiting=""
  for d in $deps; do
    if [[ "$(state_of "$d")" == "CLOSED" ]]; then continue; fi
    waiting="$waiting #$d"
    if has_label "$d" status:claimed; then
      [[ "$want" == status:ready ]] && want=status:startable
    else
      want=status:blocked
    fi
  done
  current=""
  for l in status:ready status:startable status:blocked; do has_label "$num" "$l" && current="$l"; done
  if [[ "$current" != "$want" ]]; then
    args=(--add-label "$want")
    for l in status:ready status:startable status:blocked; do
      [[ "$l" != "$want" ]] && has_label "$num" "$l" && args+=(--remove-label "$l")
    done
    gh issue edit "$num" --repo "$REPO" "${args[@]}"
    case "$want" in
      status:ready) msg="Every dependency is merged: this task is now \`status:ready\`." ;;
      status:startable) msg="Every dependency is merged or in progress:${waiting}. This task is now \`status:startable\`: you may claim it and port against the T04 stubs, but ask for review only once it turns \`status:ready\` (AGENTS.md §2)." ;;
      *) msg="Back to \`status:blocked\`: waiting on unclaimed dependencies${waiting}." ;;
    esac
    gh issue comment "$num" --repo "$REPO" --body "$msg

---
_Generated by [Claude Code](https://claude.ai/code)_"
  fi
  echo "#$num $want${waiting:+ (waiting on$waiting)}"
done
