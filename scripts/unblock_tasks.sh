#!/usr/bin/env bash
# See .github/workflows/unblock-tasks.yml. Needs GH_TOKEN and REPO.
set -euo pipefail
closed="$(gh issue list --repo "$REPO" --state closed --limit 500 --json number --jq '.[].number' | tr '\n' ' ')"
gh issue list --repo "$REPO" --state open --label type:task --label status:blocked --limit 500 \
  --json number,body --jq '.[] | @base64' |
while read -r row; do
  num="$(base64 -d <<<"$row" | jq -r .number)"
  body="$(base64 -d <<<"$row" | jq -r .body)"
  # Dependencies are the "(#N)" references in the "### Depends on" section.
  deps="$(awk '/^### Depends on/{f=1; next} /^### /{f=0} f' <<<"$body" | grep -oE '\(#[0-9]+\)' | tr -d '(#)' || true)"
  missing=""
  for d in $deps; do
    [[ " $closed " == *" $d "* ]] || missing="$missing #$d"
  done
  if [[ -z "$missing" ]]; then
    gh issue edit "$num" --repo "$REPO" --remove-label status:blocked --add-label status:ready
    gh issue comment "$num" --repo "$REPO" --body "Unblocked: every dependency is merged. This task is now \`status:ready\` (AGENTS.md §2).

---
_Generated by [Claude Code](https://claude.ai/code)_"
    echo "#$num -> ready"
  else
    echo "#$num still blocked by$missing"
  fi
done
